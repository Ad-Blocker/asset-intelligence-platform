"""
Execution Plan Dataclasses.

Defines domain models representing an ordered execution plan and individual service steps
generated by the ExecutionPlanner prior to orchestrator execution.
"""

from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional


@dataclass
class PlanStep:
    """Represents a discrete service execution step within an execution plan."""
    step_id: str
    service_name: str
    action: str
    params: Dict[str, Any] = field(default_factory=dict)
    depends_on: List[str] = field(default_factory=list)


@dataclass
class ExecutionPlan:
    """Represents a complete deterministic execution plan generated for a user query."""
    goal: str
    steps: List[PlanStep] = field(default_factory=list)
